-- EPM Data Quality Assistant
-- Combines exception details with saved remediation status.
-- This view depends on EPM_REMEDIATION_V and EPM_REMEDIATION_TRACKING.

CREATE OR REPLACE VIEW EPM_REMEDIATION_STATUS_V AS
SELECT
    r.RECORD_ID,
    r.ENTITY_CODE,
    r.ACCOUNT_CODE,
    r.PERIOD_NAME,
    r.ISSUE_TYPE,
    r.ISSUE_DETAILS,
    r.BUSINESS_EXPLANATION,
    r.RECOMMENDED_ACTION,
    NVL(t.REMEDIATION_STATUS, 'New') AS REMEDIATION_STATUS,
    t.ASSIGNED_TO,
    t.RESOLUTION_NOTES,
    t.UPDATED_AT
FROM EPM_REMEDIATION_V r
LEFT JOIN EPM_REMEDIATION_TRACKING t
    ON t.RECORD_ID = r.RECORD_ID
   AND t.ISSUE_TYPE = r.ISSUE_TYPE;
